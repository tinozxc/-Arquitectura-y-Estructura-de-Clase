package Chapter2_java_Day_3_4.day3.Capitulo3_Understanding_Java_Operators.Using_Additional_Binary_Operators;

public class RelationalOperators {

    public static void main(String[] args) {

        //Comparan dos expresiones y retornan un boolean.
        int x = 10, y = 20, z = 10;
        System.out.println(x < y);  // true
        System.out.println(x <= y); // true
        System.out.println(x >= z); // true
        System.out.println(x > z);  // false (son iguales, no "estrictamente" mayor)

        // instanceof — aplica a referencias de objetos, clases e interfaces.
    }

}
